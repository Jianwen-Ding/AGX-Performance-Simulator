#!/usr/bin/env python3
"""Exhaustive / edge-dense recording of the coverage suite's safe `convert` forms (direct DRM), for safe-01.

Forms: modes 0, 1, 4-11 x round field 0 (float -> integer) / 1 (integer -> float) x (r14 | r14l) <- (r6 | r6l): the 80
cases recorded `safe` in coverage/expected/alu/convert_*. Each kernel is load, mov r14 = 0xdeadbeef, convert, store;
its convert bytes must equal the instruction in the recorded coverage case. Inputs:
  float source (round 0), 32-bit: for each binade 2^-2 .. 2^(w+1) (w = 8 / 16 / 32 from the mode) and its negative,
    every mantissa where |x| < 4, else edge-dense mantissas (2048 at each end, 16k random, 2048 exact .5 ties with
    both neighbours); plus zeros, denormals, min normal, inf, NaN payloads, the largest finite and 4096 random words;
  float source, 16-bit (r6l): all 65,536 fp16;
  integer source (round 1), w = 8 / 16 (or r6l): all 2^16 low patterns with random upper bits in r6;
  integer source, w = 32: every value below 2^16, both signs, and per range [2^k, 2^(k+1)) 16k random values plus
    2048 exact fp32 and fp16 rounding ties with both neighbours, both signs, plus the extreme integers.
Results: /scratch/agxsim-data/convert/<form>.npz (hw; the inputs are regenerated by form_inputs). Each 2^18-lane chunk runs twice and must agree; resumable.
Usage: record_convert.py [--forms REGEX] [--list]
"""
import argparse, gzip, json, re, sys
from pathlib import Path
import numpy as np
import coverage as COV
COV.install()
import agx_loop, gpu_safety, run_bench as B, run_drm_compute as drm, record_suite as RS
import record_transcendentals as T

ROOT = Path(__file__).resolve().parents[1]
OUT = Path('/scratch/agxsim-data/convert')
FORMS = [(m, r, d, s) for m in (0, 1, 4, 5, 6, 7, 8, 9, 10, 11) for r in (0, 1)
         for d, s in (('r14', 'r6'), ('r14l', 'r6'), ('r14', 'r6l'), ('r14l', 'r6l'))]


def name(m, r, d, s):
    return f'convert_u32_to_f_{d}_{s}_rte__mode{m}_round{r}'


def instr(m, r, d, s):
    return RS.e(f'@mode={m},round={r}\tconvert u32_to_f, {d}, {s}, rte')


def body(m, r, d, s):
    b = RS.e('device_load 0, i32, x, r6, u8_u9, r1, unsigned')+RS.e('wait 0')+B.mov(14, 0xdeadbeef)
    b += instr(m, r, d, s)
    b += B.mov(27, T.CHUNK)+RS.e('iadd r26, r1, r27')+agx_loop.store(14, 8, 26)+RS.e('wait 0')+RS.e('iadd r2, r14, 0')
    return b


def recorded_bytes_ok(m, r, d, s):
    c = json.load(gzip.open(ROOT/'coverage/expected/alu'/(name(m, r, d, s)+'.json.gz')))
    return instr(m, r, d, s).hex() in c['code']


def ties(k, bits, rng, n):
    """mantissas m (x = 2^k * 1.m, 23-bit m) whose value sits exactly halfway between two multiples of 2^-bits
    (bits = fraction bits kept), plus both neighbours"""
    drop = 23-k-bits                                   # mantissa bits below the kept precision
    if drop <= 0 or drop > 23:                         # no ties: all kept, or the whole binade is below the precision
        return np.zeros(0, np.uint32)
    half = 1 << (drop-1)
    hi = rng.integers(0, 1 << (23-drop), n, dtype=np.uint64) << np.uint64(drop)
    t = (hi | np.uint64(half)).astype(np.int64)
    return np.clip(np.concatenate([t-1, t, t+1]), 0, (1 << 23)-1).astype(np.uint32)


def mant_set(k, rng, bits_list):
    """edge-dense mantissas for binade 2^k: both ends, random, and exact ties for each kept precision"""
    m = [np.arange(2048, dtype=np.uint32), np.arange((1 << 23)-2048, 1 << 23, dtype=np.uint32),
         rng.integers(0, 1 << 23, 1 << 14, dtype=np.uint32)]
    m += [ties(k, b, rng, 2048) for b in bits_list]
    return np.unique(np.concatenate(m))


def inputs(m, r, s, rng):
    w = (8, 16, 32)[m >> 2]
    if s == 'r6l' or (r == 1 and w < 32):              # 16-bit source / narrow integer: every low pattern, junk above
        lo = np.arange(1 << 16, dtype=np.uint32)
        return lo | (rng.integers(0, 1 << 16, 1 << 16, dtype=np.uint32) << 16)
    if r == 0:                                         # fp32 -> integer
        parts = []
        for k in range(-2, w+2):
            mants = np.arange(1 << 23, dtype=np.uint32) if k <= 1 else mant_set(k, rng, [0])   # ties at .5
            for sg in (0, 1):
                parts.append((np.uint32((k+127) << 23) | mants) | np.uint32(sg << 31))
        spec = [0, 0x80000000, 0x7f800000, 0xff800000, 0x7fc00000, 0xffc00000, 0x7f800001, 0x7fbfffff, 1, 0x807fffff,
                0x00800000, 0x80800000, 0x7f7fffff, 0xff7fffff]
        samp = rng.integers(0, 1 << 32, 4096, dtype=np.uint64).astype(np.uint32)
        return np.concatenate(parts+[np.array(spec, np.uint32), samp])
    # 32-bit integer -> float: every value below 2^16 (both signs); per power-of-two range, random values plus exact
    # ties for fp32 (24-bit) and fp16 (11-bit) results and their neighbours
    parts = [np.arange(1 << 16, dtype=np.uint32), (-np.arange(1 << 16, dtype=np.int64)).astype(np.uint32)]
    for k in range(16, 32):
        v = [rng.integers(1 << k, (1 << (k+1))-1, 1 << 14, dtype=np.uint64)]
        for keep in (24, 11):
            d = k+1-keep
            if d > 0:
                base = rng.integers(0, 1 << (keep-1), 2048, dtype=np.uint64)
                t = (np.uint64(1 << k) | (base << np.uint64(d)) | np.uint64(1 << (d-1))).astype(np.int64)
                v.append(np.concatenate([t-1, t, t+1]).astype(np.uint64))
        v = np.concatenate(v)
        v = v[v < (1 << 32)]
        parts += [v.astype(np.uint32), (-(v.astype(np.int64))).astype(np.uint32)]
    parts.append(np.array([0x7fffffff, 0x80000000, 0xffffffff, 0x80000001, 0x00ffffff, 0x01000001, 0xff000001], np.uint32))
    return np.concatenate(parts)


def form_inputs(f):
    """the deterministic input words of form f = (mode, round, dst, src)"""
    return inputs(f[0], f[1], f[3], np.random.default_rng(list(f[:2])+[len(f[2]), len(f[3])]))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--forms', default='.')
    ap.add_argument('--list', action='store_true')
    a = ap.parse_args()
    forms = [f for f in FORMS if re.search(a.forms, name(*f))]
    if a.list:
        for f in forms:
            print(name(*f), len(form_inputs(f)))
        return
    OUT.mkdir(parents=True, exist_ok=True)
    R = B.Runner(Path('/scratch/apple-m2-playground/sim/convert'))
    C = T.CHUNK
    for f in forms:
        path = OUT/(name(*f)+'.npz')
        if path.exists():
            continue
        if not recorded_bytes_ok(*f):
            sys.exit(f'{name(*f)}: encoding differs from the recorded coverage case; refusing')
        RS.gate(body(*f))
        gpu_safety.require_budget(1)
        code = drm.build_main(body(*f))
        xs = form_inputs(f)
        sim_gate(f, code, xs)
        hw = np.zeros(len(xs), np.uint32)
        for s0 in range(0, len(xs), C):
            part = [int(x) for x in xs[s0:s0+C]]
            n = len(part)
            table = part+[0]*(C-n)+[0]*C
            res = [run(R, code, C, T.WG, table)[1] for _ in range(2)]
            if res[0] != res[1]:
                raise RuntimeError(f'{name(*f)} chunk {s0}: runs disagree')
            hw[s0:s0+n] = res[0][C:C+n]
        np.savez_compressed(path, hw=hw)     # inputs: regenerate with inputs(...) and the form's seed (see seed())
        print(json.dumps({'form': name(*f), 'inputs': len(xs)}), flush=True)


def sim_gate(f, code, xs, n=4096):
    """Pre-GPU gate: the exact kernel runs in agx_run (simulator) on a sample of the form's inputs (first, last and
    random words, one 2^18-lane chunk layout) and must equal the convert model (convert_check.model)."""
    import convert_check as CC
    rng = np.random.default_rng(1)
    pick = np.unique(np.concatenate([np.arange(min(n, len(xs))), np.arange(max(0, len(xs)-n), len(xs)),
                                     rng.integers(0, len(xs), n)]))
    sample = xs[pick]
    C = T.CHUNK
    table = [int(x) for x in sample]+[0]*(C-len(sample))+[0]*C
    _, tab = COV.simulate(code, C, T.WG, 64, 0, table)
    got = np.array(tab[C:C+len(sample)], np.uint32)
    want = CC.model(*f, sample).astype(np.uint32)
    bad = int(np.sum(got != want))
    if bad:
        raise RuntimeError(f'{name(*f)}: simulator differs from the convert model on {bad} of {len(sample)} sampled inputs; refusing')
    return len(sample)


run = RS.run
if __name__ == '__main__':
    sys.exit(main())
