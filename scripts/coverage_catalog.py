FORMATS = ['i8', 'i16', 'i32', 'f16', 'u8norm', 's8norm', 'u16norm', 's16norm', 'rgb10a2', 'srgba8', 'rg11b10f', 'rgb9e5']
PACKED = ('rgb10a2', 'rg11b10f', 'rgb9e5')


def mem_forms():
    """(load text, finding, risk): every format x component mask x 16/32-bit registers, shifts, signedness, bases"""
    out = []
    for fmt in FORMATS:
        tried = fmt in ('i8', 'i16', 'i32', 'u8norm')
        risk = 'safe' if tried or fmt in ('f16', 's8norm', 'u16norm', 's16norm') else 'may_fault'
        for mask in ('x', 'y', 'z', 'w', 'xy', 'xz', 'yw', 'zw', 'xyz', 'xyzw'):
            n = len(mask)
            if fmt != 'i32':
                regs16 = '_'.join(f'r{14 + k // 2}{"lh"[k % 2]}' for k in range(n))
                out.append((f'device_load 0, {fmt}, {mask}, {regs16}, u8_u9, r5, unsigned', 'memory-hierarchy', risk))
            if fmt not in ('i8', 'i16'):
                regs32 = '_'.join(f'r{14 + k}' for k in range(n))
                out.append((f'device_load 0, {fmt}, {mask}, {regs32}, u8_u9, r5, unsigned', 'memory-hierarchy', risk))
        for sh in ('', ', lsl 1', ', lsl 2', ', lsl 3'):
            for mode in ('unsigned', 'signed'):
                r = 'r14' if fmt not in ('i8', 'i16') else 'r14l'
                out.append((f'device_load 0, {fmt}, x, {r}, r24_r25, r5, {mode}{sh}', 'memory-hierarchy', risk))
        out.append((f'device_load 1, {fmt}, x, {"r14" if fmt not in ("i8", "i16") else "r14l"}, u8_u9, 7, unsigned', 'memory-hierarchy', risk))
    return out


