# Case construction (uses record_suite.py helpers; imported lazily so the catalog itself has no GPU dependency)

def _rs():
    import record_suite
    return record_suite


def alu_case(t, finding, risk, masked=False):
    def build(t=t, masked=masked):
        RS = _rs()
        rng = random.Random('coverage:' + t)
        table = [RS.operand(rng) for _ in range(8 * N)] + [0] * (2 * N)
        instr = RS.e(t, _want(t)) if _want(t) else RS.e(t)
        return ('alu_masked' if masked else 'alu', _name(t), t, RS.alu_body(instr, N, masked), N, WG, 64, 0, table)
    area = 'alu_masked' if masked else 'alu'
    return Case(f'{area}/{_name(t)}', area, finding, risk, 'functional', t, build, [(t, _want(t))])


def lane_text(width, k, g=0):
    """10-byte fmadd lane-offset form (bit 53): k = lane offset (bits 75-79), g = bits 64-74. Only the measured subset
    (playground 2026-10-11-fmadd-lane-offset, 2026-10-18-fmadd-followups): default 16-lane halves, k <= 16, and for fmadd16
    the 2- / 4-lane groups (bits 72 / 73) with k = 1. The cross-half read (bit 68) is timing-dependent and is not covered."""
    regs = ('r14', 'r6', 'r7', 'r8') if width == 32 else ('r14l', 'r6l', 'r7l', 'r8l')
    return f"fmadd{width}_lane {', '.join(regs)}, 0b{k:05b}, 0b{g:011b}, 0b0"


def lane_cases():
    forms = [(w, k, 0) for w in (32, 16) for k in (0, 1, 2, 4, 8, 15, 16)] + [(16, 1, 1 << 8), (16, 1, 1 << 9)]
    out = []
    for w, k, g in forms:
        t = lane_text(w, k, g)
        out.append(lane_case(t, 'fmadd-lane-offset', False))
    for w in (32, 16):
        for k in (1, 2, 4, 8):
            out.append(lane_case(lane_text(w, k), 'fmadd-lane-offset', True))
    return out


def lane_b18_cases():
    """ptx-re-blockers B18: the remaining forms agx.fma_lane_shift may emit. Every k = 1..15 at the default 16-lane width
    (both widths), 4-lane segments (bit 73) with k = 1..3 and 2-lane segments (bit 72) with k = 1 for fmadd16 and fmadd32,
    and partial masks for the k not yet masked. Areas fmadd_lane_b18 and fmadd_lane_b18_masked."""
    have = {(w, k) for w in (32, 16) for k in (0, 1, 2, 4, 8, 15, 16)}
    forms = [(w, k, 0, False) for w in (32, 16) for k in range(1, 16) if (w, k) not in have]
    forms += [(w, k, 1 << 9, False) for w in (32, 16) for k in (1, 2, 3) if not (w == 16 and k == 1)]
    forms += [(32, 1, 1 << 8, False)]
    forms += [(w, k, 0, True) for w in (32, 16) for k in (3, 5, 7, 15)]
    return [lane_case(lane_text(w, k, g), 'fmadd-lane-offset', m, 'fmadd_lane_b18_masked' if m else 'fmadd_lane_b18') for w, k, g, m in forms]


def lane_case(t, finding, masked, area=None):
    area = area or ('fmadd_lane_masked' if masked else 'fmadd_lane')

    def build(t=t, masked=masked, area=area):
        RS = _rs()
        rng = random.Random('coverage:' + area + t)
        table = [RS.operand(rng) for _ in range(8 * N)] + [0] * (2 * N)
        return (area, _name(t), t, RS.alu_body(RS.e(t), N, masked), N, WG, 64, 0, table)
    return Case(f'{area}/{_name(t)}', area, finding, 'safe', 'functional', t, build, [(t, None)])


