ITEM_BYTES = {'i8': 1, 'i16': 2, 'i32': 4, 'f16': 2, 'u8norm': 1, 's8norm': 1, 'u16norm': 2, 's16norm': 2}   # packed: 4


def mem_parts(t):
    """device_load text -> (fmt, mask, mode, shift text, base, index operand)"""
    p = t.split(', ')
    sh = ', ' + p[7] if len(p) > 7 else ''
    return p[1], p[2], p[6], sh, p[4], p[5]


def _bounds(fmt, mask, sh, base, rng_idx, table_words):
    shift = int(sh.split()[-1]) if sh else 0
    item = ITEM_BYTES.get(fmt, 4)
    comps = max('xyzw'.index(c) for c in mask) + 1
    off0 = 8192 if base == 'r24_r25' else 0
    lo = off0 + (rng_idx[0] << shift) * item
    hi = off0 + ((rng_idx[1] << shift) + comps) * max(item, 4)
    if lo < 0 or hi > 4 * table_words:
        raise ValueError(f'out of table: {fmt} {mask} {sh} {base}: bytes {lo}..{hi}')


def mem_load_case(t, finding, risk):
    """the suite's mem_load layout: r5 index (unsigned (gid*37 & 255) + 3 / signed around the base), 4 result words"""
    def build(t=t):
        RS = _rs()
        fmt, mask, mode, sh, base, index = mem_parts(t)
        rng = random.Random('coverage:' + t)
        table = [rng.getrandbits(32) for _ in range(8192)] + [0] * (4 * N)
        idx, rng_idx = RS.load_index(mode, base)
        _bounds(fmt, mask, sh, base, rng_idx if index == 'r5' else (int(index), int(index)), 8192)
        b = RS.mem_prologue(N) + idx + RS.e(t) + RS.e('wait 0')
        b += RS.mov(27, 8192) + RS.mov(26, 4) + RS.e('imadd r26, r1, r26, r27')
        for k in range(4):
            b += RS.agx_loop.store(14 + k, 8, 26) + RS.e('iadd r26, r26, 1')
        b += RS.e('wait 0') + RS.e('iadd r2, r14, 0')
        return ('mem_load', _name(t), t, b, N, WG, 64, 0, table)
    return Case(f'mem_load/{_name(t)}', 'mem_load', finding, risk, 'functional', t, build, [(t, None)])


def mem_store_case(t, finding, risk):
    """the suite's mem_store layout: distinct per-SIMD-group targets, values (gid << 8) | 0x11*(k+1)"""
    def build(t=t):
        RS = _rs()
        fmt, mask, mode, sh, base, index = mem_parts(t)
        rng = random.Random('coverage-store:' + t)
        table = [rng.getrandbits(32) for _ in range(12288)]
        shift = int(sh.split()[-1]) if sh else 0
        lo = -(8192 // (ITEM_BYTES.get(fmt, 4) << shift)) // 4 if mode == 'signed' and base == 'r24_r25' else 0   # -512 for i32
        m = (2 if shift == 0 else 1) * (2 if ITEM_BYTES.get(fmt, 4) < 4 and len(mask) > 2 else 1)
        b = RS.mem_prologue(N)
        b += RS.mov(27, 5) + RS.e('asr r28, r1, r27') + RS.mov(27, m) + RS.e('imadd r5, r1, r27, 0') + RS.e('imadd r5, r28, r27, r5')
        if lo:
            b += RS.mov(27, lo & 0xffffffff) + RS.e('iadd r5, r5, r27')
        _bounds(fmt, mask, sh, base, (lo, lo + m * (N - 1 + (N - 1) // 32)), 12288)
        for k in range(4):
            b += RS.mov(26, 256) + RS.e(f'imadd r{14 + k}, r1, r26, 0') + RS.mov(26, 0x11 * (k + 1)) + RS.e(f'or r{14 + k}, r{14 + k}, r26')
        b += RS.store_like(t) + RS.e('wait 0') + RS.e('iadd r2, r1, 0')
        return ('mem_store', 'store_' + _name(t), 'device_store with the fields of: ' + t, b, N, WG, 64, 0, table)
    return Case(f'mem_store/store_{_name(t)}', 'mem_store', finding, risk, 'functional', 'device_store like ' + t, build, [(t, None)])


def sr_case(n, geom):
    gx, gy, gz, lx, ly, lz = geom
    name = f'sr{n}_{gx}x{gy}x{gz}_wg{lx}x{ly}x{lz}'
    def build(n=n, geom=geom):
        RS = _rs()
        count = geom[0]
        b = RS.B.get_sr(n, 14) + RS.mov(27, 8192) + RS.e('iadd r26, r1, r27') + RS.agx_loop.store(14, 8, 26)
        b += RS.e('wait 0') + RS.e('iadd r2, r14, 0')
        table = [0] * (8192 + geom[0] * geom[1] * geom[2] + 64)
        return ('geometry', name, f'get_sr sr{n} per thread, grid {geom[:3]} workgroup {geom[3:]}', b, count, geom[3], 64, 0, table, None, geom)
    # every selector 0..255 has been read with this get_sr encoding without a fault (126+ direct-DRM full scans, the
    # 2026-10-16 divergence / VM-slot runs, and the recorded geometry cases), so all are safe to read; _sr_known()
    # only decides which selectors run under all launch geometries
    risk = 'safe'
    return Case(f'geometry/{name}', 'geometry', 'sr-geometry-core-id / sr-resource-registers / sr17-sr32', risk, 'functional',
                f'special register {n} under launch {geom}', build, [])


def control_cases():
    """if/else/while with every condition code, push counts, nesting depth, jmp_exec_none and aliases"""
    out = []
    specs = []
    for cc in ICC.values():
        specs.append((f'if_icmp_{cc}', f'if_icmp r0l, {cc}, r6, r7, 1', f'else_icmp r0l, ult, r6, r7, 1'))
        specs.append((f'while_icmp_{cc}', None, f'while_icmp r0l, {cc}, r3, r20, 1'))
    for cc in FCC.values():
        specs.append((f'if_fcmp_{cc}', f'if_fcmp r0l, {cc}, r10, r11, 1', f'else_fcmp r0l, lt, r10, r11, 1'))
        specs.append((f'while_fcmp_{cc}', None, f'while_fcmp r0l, {cc}, r22, r10, 1'))
    for name, if_t, else_t in specs:
        def build(name=name, if_t=if_t, else_t=else_t):
            RS = _rs()
            A = lambda k: RS.e(f'iadd r2, r2, {k}')
            load = RS.mov(27, 8) + RS.e('imadd r5, r1, r27, 0') + RS.e('iadd r26, r5, 4')
            load += RS.e('device_load 0, i32, xyzw, r6_r7_r8_r9, u8_u9, r5, unsigned')
            load += RS.e('device_load 0, i32, xyzw, r10_r11_r12_r13, u8_u9, r26, unsigned') + RS.e('wait 0') + RS.mov(2, 1000)
            if if_t:
                body = RS.if_else(if_t, else_t, A(1), A(2))
            else:
                # bounded do-while: counter r3 vs r20 = (r6 & 7) + 1 (integer) or x += 0.5 (float)
                lp = RS.e('iadd r2, r2, r3') + RS.e('iadd r3, 1, r3.sx') + RS.mov(27, 0x3f000000) + RS.e('fadd32 r22, r22, r27')
                lp += RS.e(else_t)
                head = RS.mov(3, 0) + RS.mov(22, 0) + RS.mov(27, 7) + RS.e('and r20, r6, r27') + RS.e('iadd r20, r20, 1')
                head += RS.e('if_fcmp r0l, eq, 0.0, 0.0, 1', 'push_exec r0l, 1')
                body = head + lp + RS.e(f'jmp_exec_any pc-{len(lp)}', f'jmp_exec_any pc-{len(lp)}') + RS.e('pop_exec r0l, 1')
            b = load + body + RS.e('iadd r2, r2, 0')
            rng = random.Random(name)
            table = []
            for _ in range(N):
                table += [rng.randrange(64) for _ in range(4)] + [struct.unpack('<I', struct.pack('<f', rng.uniform(-4, 4)))[0] for _ in range(2)] + [rng.randrange(64) for _ in range(2)]
            return ('control', name, f'{if_t or else_t}', b, N, WG, 64, 0, table)
        texts = [(t, None) for t in (if_t, else_t) if t]
        # while_* is not bounded for every condition: with r3 counting up from 1 and r20 in 1..8, `while_icmp ugte`
        # never exits (r3 >= r20 stays true). It hung the M2 on 2026-10-12: the display froze until the GPU recovered
        # (no reboot), and the 11 dispatches sent meanwhile timed out. Until each condition's loop is proven to terminate, all
        # while_* cases are may_fault.
        risk = 'may_fault' if name.startswith('while_') else 'safe'
        out.append(Case(f'control/{name}', 'control', 'cf-float / exec-control-cost', risk, 'functional', name, build, texts))
    # The same while_* loops with a guard that bounds them whatever the condition under test does: the last instruction
    # of the body is `while_icmp r0l, ult, r28, r29, 1` (the recorded agx_loop form) on a per-lane trip counter r28, so
    # every lane with r0l <= 1 is off after WHILE_GUARD trips, both if `while` evaluates only active lanes (the
    # simulator's reading) and if it re-evaluates r0l == 1 lanes. Lanes with r0l >= 2 stay off (agx_loop partial-SIMD-
    # group runs). r10 holds NaN / +-inf in some lanes, so the NaN-aware float conditions are exercised too.
    for kind, cc in [('icmp', c) for c in ICC.values()] + [('fcmp', c) for c in FCC.values()]:
        t = f'while_fcmp r0l, {cc}, r22, r10, 1' if kind == 'fcmp' else f'while_icmp r0l, {cc}, r3, r20, 1'
        name = f'while_guard_{kind}_{cc}'
        def build(name=name, t=t):
            RS = _rs()
            load = RS.mov(27, 8) + RS.e('imadd r5, r1, r27, 0') + RS.e('iadd r26, r5, 4')
            load += RS.e('device_load 0, i32, xyzw, r6_r7_r8_r9, u8_u9, r5, unsigned')
            load += RS.e('device_load 0, i32, xyzw, r10_r11_r12_r13, u8_u9, r26, unsigned') + RS.e('wait 0') + RS.mov(2, 1000)
            lp = RS.e('iadd r2, r2, r3') + RS.e('iadd r3, 1, r3.sx') + RS.mov(27, 0x3f000000) + RS.e('fadd32 r22, r22, r27')
            lp += RS.e('iadd r28, 1, r28.sx') + RS.e(t) + RS.e('while_icmp r0l, ult, r28, r29, 1')
            head = RS.mov(3, 0) + RS.mov(22, 0) + RS.mov(28, 0) + RS.mov(29, WHILE_GUARD)
            head += RS.mov(27, 7) + RS.e('and r20, r6, r27') + RS.e('iadd r20, r20, 1')
            head += RS.e('if_fcmp r0l, eq, 0.0, 0.0, 1', 'push_exec r0l, 1')
            body = head + lp + RS.e(f'jmp_exec_any pc-{len(lp)}', f'jmp_exec_any pc-{len(lp)}') + RS.e('pop_exec r0l, 1')
            b = load + body + RS.e('iadd r2, r2, r28')
            rng = random.Random(name)
            special = [0x7fc00000, 0x7f800000, 0xff800000, 0x00000000, 0x80000000, 0x41000000]   # NaN, +-inf, +-0, 8.0
            table = []
            for i in range(N):
                f0 = special[i % 8] if i % 8 < len(special) and i % 3 == 0 else struct.unpack('<I', struct.pack('<f', rng.uniform(-4, 4)))[0]
                table += [rng.randrange(64) for _ in range(4)] + [f0, struct.unpack('<I', struct.pack('<f', rng.uniform(-4, 4)))[0]]
                table += [rng.randrange(64) for _ in range(2)]
            return ('control', name, f'{t} + guard while_icmp ult r28 < {WHILE_GUARD}', b, N, WG, 64, 0, table)
        out.append(Case(f'control/{name}', 'control', 'cf-float / exec-control-cost', 'may_fault', 'functional', name, build,
                        [(t, None)]))
    # nesting depth 1..8 (r0l counter) and push counts n = 1..3
    for depth in range(1, 9):
        def build(depth=depth):
            RS = _rs()
            b = RS.mov(27, 8) + RS.e('imadd r5, r1, r27, 0') + RS.e('device_load 0, i32, xyzw, r6_r7_r8_r9, u8_u9, r5, unsigned') + RS.e('wait 0')
            b += RS.mov(2, 0)
            inner = RS.e('iadd r2, r2, 1')
            for k in range(depth):
                reg = 6 + (k % 4)
                inner = RS.if_else(f'if_icmp r0l, ult, r{reg}, r24, 1', None, RS.e('iadd r2, r2, 1') + inner, b'')
            b += RS.mov(24, 32) + inner
            rng = random.Random(f'nest{depth}')
            return ('control', f'nest_depth{depth}', f'{depth} nested ifs on r6..r9 < 32', b, N, WG, 64, 0, [rng.randrange(64) for _ in range(8 * N)])
        out.append(Case(f'control/nest_depth{depth}', 'control', 'exec-control-cost', 'safe', 'functional', f'if nesting depth {depth}', build, []))
    for n in (1, 2, 3):
        t = f'if_icmp r0l, ult, r6, r7, {n}'
        def build(t=t, n=n):
            RS = _rs()
            b = RS.mov(27, 8) + RS.e('imadd r5, r1, r27, 0') + RS.e('device_load 0, i32, xyzw, r6_r7_r8_r9, u8_u9, r5, unsigned') + RS.e('wait 0')
            b += RS.mov(2, 0) + RS.e(t) + RS.e('iadd r2, r2, 1') + RS.e(f'pop_exec r0l, {n}') + RS.e('iadd r2, r2, r0')
            rng = random.Random(t)
            return ('control', f'push_count_{n}', t + ' then pop_exec n', b, N, WG, 64, 0, [rng.randrange(64) for _ in range(8 * N)])
        out.append(Case(f'control/push_count_{n}', 'control', 'exec-control-cost', 'safe', 'functional', t, build, [(t, None)]))
    return out


