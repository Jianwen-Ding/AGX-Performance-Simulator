"""AGX coverage catalog: one test case per known behaviour of the G14 (M2) GPU, with no expected values.

Every case says what it exercises, which finding it comes from, and how risky it is to run:
  safe       forms that already ran on hardware (or plain variations of them: other registers, operands, sizes)
  may_fault  encodings never run, or close to ones that hung the GPU (funop functions 2/3/5/7/11/15, convert with
             bit 27, icond 3/7 and fcond 4 "never" codes, unknown sub-ops, undecoded opcodes). Recorded only with
             `coverage.py record --risky`, one dispatch at a time under the gpu_safety hang budget.
Functional cases produce the test-suite tuple of record_suite.py (category, name, description, body, lanes, wg,
regs, shared bytes, table[, oracle, dims]) and are recorded in the same file format, so `suite_check` checks them.
Timing cases name an instruction-bench form (latency / SIMD issue / per-core throughput, run_bench.py).

The catalog is generated by code (CASES) so that a new form is one line in a table below. `coverage.py validate`
assembles every case offline with the Rust assembler (identical to applegpu's), so the catalog can be checked
without the GPU.
"""
import random, struct
from dataclasses import dataclass, field
from typing import Callable, Optional

N, WG = 1024, 256


@dataclass
class Case:
    id: str                    # unique: <area>/<name>
    area: str
    finding: str               # source finding (novel-results/... in Apple-M2-Playground or this repository)
    risk: str                  # safe | may_fault
    kind: str                  # functional | timing
    description: str
    build: Callable = None     # () -> record_suite tuple (functional) or bench template dict (timing)
    texts: list = field(default_factory=list)   # assembly lines the case needs (validated offline)


def _name(t):
    """file-name form of an assembly line ('@F=V\tTEXT' raw forms: 'TEXT__F=V')"""
    if t.startswith('@'):
        spec, text = t[1:].split('\t', 1)
        t = text + '__' + spec.replace(',', '_')
    return (t.replace(' ', '_').replace(',', '').replace('.', '-').replace('/', '_').replace('=', ''))[:120]


def raw(spec, text):
    """a raw encoding: TEXT assembled, then decode fields / bit ranges (bSTART_SIZE) set (agx_asm '@' syntax)"""
    return f'@{spec}\t{text}'


ICC = {0: 'ueq', 1: 'ult', 2: 'ugt', 4: 'seq', 5: 'slt', 6: 'sgt', 8: 'nueq', 9: 'ugte', 10: 'ulte', 12: 'nseq', 13: 'sgte', 14: 'slte'}
FCC = {0: 'eq', 1: 'lt', 2: 'gt', 3: 'ltn', 5: 'gte', 6: 'lte', 7: 'gtn', 8: 'neq', 9: 'nlt', 10: 'ngt', 13: 'ngte', 14: 'nlte'}
WHILE_GUARD = 20   # trip bound of the guarded while_* cases (control_cases)


def cc_form(base, cc, float_):
    """base has '{cc}' where the condition goes; named code when there is one, else the raw field (cc, ccn)"""
    names = FCC if float_ else ICC
    if cc in names:
        return base.format(cc=names[cc]), 'safe'
    spec = f'cc={cc & 7}' + (f',ccn={cc >> 3}' if cc > 7 else '')
    return raw(spec, base.format(cc=names[1])), 'may_fault'


