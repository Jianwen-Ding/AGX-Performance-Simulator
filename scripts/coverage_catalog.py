# ALU forms. Sources r6..r13 come from the per-lane table (record_suite.operand: float specials, fp16 pairs, edge
# integers, random), destination r14 (r14l 16-bit, r14_r15 64-bit), as in the hardware suite's alu category.

F32_IMM = ['0.0', '-0.0', '0.5', '-2.0', '31.0', '0.015625']
UNIFORM = ['u5', 'u4']                 # u5 = lane count, u4 = 0 (harness uniforms)
I16 = ['r6l', 'r6h']


def _int_sources(slot):
    """operand variants for an integer source slot (r6 base)"""
    return ['r6', 'r6l', 'r6h', 'r6.sx', 'r6l.sx', 'r6.cache', 'r6.discard', 'u5', 'u5l', '0', '1', '255']


def alu_forms():
    """(text, finding, risk) for every ALU form in the coverage matrix."""
    F = []
    add = lambda t, f='subop-spaces', r='safe': F.append((t, f, r))
    # integer add / sub: destination sizes, every source kind in A and in B, shifts 0..7, saturation, 64-bit
    for op in ('iadd', 'isub'):
        for d in ('r14', 'r14l', 'r14_r15'):
            add(f'{op} {d}, r6, r7')
        for a in _int_sources('A') + ['r6_r7']:
            add(f'{op} r14_r15, {a}, r8' if a == 'r6_r7' else f'{op} r14, {a}, r8')
        for b in _int_sources('B'):
            add(f'{op} r14, r6, {b.replace("r6", "r7")}')
        for s in range(1, 8):
            add(f'{op} r14, r6, r7, lsl {s}')
        add(f'{op}.sat r14, r6, r7'); add(f'{op}.sat r14, r6.sx, r7.sx'); add(f'{op}.sat r14l, r6l, r7l')
        add(f'{op}.sat r14l, r6l.sx, r7l.sx'); add(f'{op}.sat r14, r6, r7, lsl 1')
        add(f'{op} r14_r15, r6_r7, r8_r9, lsl 3'); add(f'{op} r14_r15, r6.sx, r8_r9')
    # multiply-add
    for op in ('imadd', 'imsub'):
        for d in ('r14', 'r14l', 'r14_r15'):
            add(f'{op} {d}, r6, r7, r8')
        for a in ('r6l', 'r6h', 'r6.sx', 'r6l.sx', 'u5', '3', '255'):
            add(f'{op} r14, {a}, r7, r8')
        for c in ('r8l', 'r8.sx', 'r8_r9', 'u5', '0', '200'):
            add(f'{op} r14_r15, r6, r7, {c}' if c == 'r8_r9' else f'{op} r14, r6, r7, {c}')
        for s in range(1, 8):
            add(f'{op} r14, r6, r7, r8, lsl {s}')
        add(f'{op}.sat r14, r6, r7, r8'); add(f'{op}.sat r14, r6.sx, r7.sx, r8.sx'); add(f'{op} r14_r15, r6.sx, r7.sx, r8_r9')
    # bitwise: every truth table (bitop aliases), 16-bit and immediate forms
    for tt in range(16):
        add(f'bitop {tt:04b}, r14, r6, r7')
    for op in ('and', 'or', 'xor', 'nand', 'nor', 'xnor'):
        add(f'{op} r14l, r6h, r7l'); add(f'{op} r14, u5, r7'); add(f'{op} r14, r6, 0')
    add('not r14, r6l'); add('mov r14, u5'); add('mov r14l, r6h')
    # bit fields and shifts
    for op in ('bfi', 'bfeil', 'extr', 'shlhi', 'shrhi'):
        for c in ('r8', '0', '1', '31', '32', '33', '63', '64', '127'):
            add(f'{op} r14, r6, r7, {c}')
        for m in ('0x1', '0xFF', '0xFFFF', '0x7FFFFFFF'):
            add(f'{op} r14, r6, r7, r8, mask {m}')
        add(f'{op} r14l, r6l, r7l, r8l')
    for op in ('asr', 'asrh'):
        for b in ('r8', '0', '1', '31', '32', '63', '64', '127', 'r8l', 'u5'):
            add(f'{op} r14, r6, {b}')
        add(f'{op} r14, r6l, r8'); add(f'{op} r14l, r6l, r8')
    for op in ('bitrev', 'popcount', 'ffs'):
        for a in ('r6', 'r6l', 'r6h', 'u5', '0', '255'):
            add(f'{op} r14, {a}');
        add(f'{op} r14l, r6l')
    for a, b in (('r6', 'r7'), ('r6l', 'r7h'), ('u5', 'r7'), ('r6', '255'), ('0', 'r7')):
        add(f'intl r14, {a}, {b}')
    add('intl r14l, r6l, r7l')
    # unknown integer unary sub-ops (iunop op1/op2 outside bitrev/popcount/ffs)
    for op1 in range(4):
        for op2 in range(4):
            if (op1, op2) in ((0, 1), (0, 2), (0, 3)):
                continue
            add(raw(f'b38_2={op1},b26_2={op2}', 'bitrev r14, r6'), 'subop-spaces', 'may_fault')
    # float add / mul / fma, 32 and 16 bit: modifiers on every source, immediates, uniforms, saturation, sizes
    MODS = ['', '.abs', '.neg', '.abs.neg']
    for op in ('fadd32', 'fmul32'):
        for d in ('r14', 'r14l'):
            add(f'{op} {d}, r6, r7', 'float-semantics')
        for ma in MODS:
            for mb in MODS:
                add(f'{op} r14, r6{ma}, r7{mb}', 'float-semantics')
        for imm in F32_IMM:
            add(f'{op} r14, r6, {imm}', 'float-semantics'); add(f'{op} r14, {imm}, r7', 'float-semantics')
        for a in ('r6l', 'r6h', 'u5', 'r6.cache', 'r6.discard'):
            add(f'{op} r14, {a}, r7', 'float-semantics')
        add(f'{op}.sat r14, r6.neg, r7', 'float-semantics'); add(f'{op}.sat r14l, r6l, r7', 'float-semantics')
    for op in ('fadd16', 'fmul16'):
        for ma in MODS:
            add(f'{op} r14l, r6l{ma}, r7h', 'float-semantics')
        for imm in F32_IMM:
            add(f'{op} r14l, r6l, {imm}', 'float-semantics')
        add(f'{op} r14l, u5l, r7l', 'float-semantics'); add(f'{op}.sat r14l, r6h, r7l', 'float-semantics')
    for op, d, a, b, c in (('fmadd32', 'r14', 'r6', 'r7', 'r8'), ('fmadd16', 'r14l', 'r6l', 'r7l', 'r8l')):
        for ma in MODS:
            add(f'{op} {d}, {a}{ma}, {b}, {c}', 'float-semantics'); add(f'{op} {d}, {a}, {b}, {c}{ma}', 'float-semantics')
        for imm in F32_IMM[:4]:
            add(f'{op} {d}, {a}, {imm}, {c}', 'float-semantics'); add(f'{op} {d}, {a}, {b}, {imm}', 'float-semantics')
        add(f'{op}.sat {d}, {a}, {b}, {c}', 'float-semantics')
    add('fmadd32 r14l, r6, r7, r8', 'float-semantics'); add('fmadd32 r14, r6l, r7h, r8', 'float-semantics')
    # float unary functions: named (with sizes, modifiers, saturation) and every funop function code
    for f in ('floor', 'ceil', 'trunc', 'rint', 'rcp', 'rsqrt', 'rsqrt_special', 'log2', 'exp2', 'sin_pt_1', 'sin_pt_2'):
        for a in ('r6', 'r6.abs', 'r6.neg', 'r6l', 'u5', '0.5', '-2.0'):
            add(f'{f} r14, {a}', 'subop-spaces')
        add(f'{f} r14l, r6h', 'subop-spaces'); add(f'{f}.sat r14, r6', 'subop-spaces')
    # every funop function code (named ones included, as raw edits of floor; 4 = dfdx, 6 = dfdy in a compute shader)
    for code in range(64):
        risky = code in (2, 3, 5, 7, 11, 15) or code not in (0, 1, 8, 9, 10, 12, 13, 14, 16, 32, 48)
        add(raw(f'b28_6={code}', 'floor r14, r6'), 'subop-spaces', 'may_fault' if risky else 'safe')
    # convert: every mode code in both directions, 16/32-bit destinations and sources
    # (mode field 0..15; round field: bit 26 = direction float->int / int->float, bit 27 hung the GPU -> may_fault)
    for mode in range(16):
        for rnd in range(4):
            risky = mode in (2, 3) or mode > 11 or rnd > 1
            for d, s in (('r14', 'r6'), ('r14l', 'r6'), ('r14', 'r6l'), ('r14l', 'r6l')):
                add(raw(f'mode={mode},round={rnd}', f'convert u32_to_f, {d}, {s}, rte'), 'subop-spaces', 'may_fault' if risky else 'safe')
    # compare-select: every condition code, sizes, X/Y operand kinds
    for cc in range(8):
        for base, fl in (('icmpsel {cc}, r14, r6, r7, r8, r9', False), ('icmpsel {cc}, r14l, r6l, r7h, r8l, r9h', False),
                         ('fcmpsel {cc}, r14, r6, r7, r8, r9', True), ('fcmpsel {cc}, r14l, r6l, r7l, r8l, r9l', True)):
            t, risk = cc_form(base, cc, fl)
            add(t, 'subop-spaces', risk)
    for x, y in (('0', '255'), ('u5', 'r9'), ('r8.cache', 'r9.discard')):
        add(f'icmpsel ult, r14, r6, r7, {x}, {y}', 'subop-spaces'); add(f'fcmpsel lt, r14, r6.abs, r7.neg, {x}, {y}', 'float-semantics')
    # ballots: every condition including the inverted ones; quad ballots
    for cc in range(16):
        for base, fl in (('icmp_ballot r14, {cc}, r6, r7', False), ('icmp_quad_ballot r14, {cc}, r6, r7', False),
                         ('fcmp_ballot r14, {cc}, r6, r7', True), ('fcmp_quad_ballot r14, {cc}, r6, r7', True)):
            t, risk = cc_form(base, cc, fl)
            add(t, 'subop-spaces', risk)
    add('icmp_ballot r14l, ult, r6l, r7l', 'subop-spaces'); add('icmp_ballot r14, ult, r6, 7', 'subop-spaces')
    # shuffles: every index source; 16-bit and 64-bit data
    for s in ('simd_shuffle', 'simd_shuffle_down', 'simd_shuffle_up', 'simd_shuffle_xor', 'simd_shuffle_rotate_up',
              'quad_shuffle', 'quad_shuffle_down', 'quad_shuffle_up', 'quad_shuffle_xor', 'quad_shuffle_rotate_up'):
        for b in ('r7l', 'r7h', '0', '1', '4', '31', '32', '255', 'u5l'):
            add(f'{s} r14, r6, {b}', 'subop-spaces')
        add(f'{s} r14l, r6l, r7l', 'subop-spaces')
    for s in ('quad_shuffle', 'quad_shuffle_xor'):
        add(f'{s} r14, r6_r7, 1', 'subop-spaces')
    # reductions and prefix ops: 16-bit and 64-bit sources, 16-bit destinations
    RED = ['and', 'or', 'xor', 'iadd', 'fadd', 'fmul', 'min.u', 'max.u', 'min.s', 'max.s', 'min.f', 'max.f']
    for scope in ('simd', 'quad'):
        for op in RED:
            add(f'{scope}_{op} r14l, r6l', 'subop-spaces'); add(f'{scope}_{op} r14, r6_r7', 'subop-spaces')
    for op in ('iadd', 'fadd', 'fmul', 'and', 'or', 'xor', 'min.s', 'min.u', 'max.s', 'max.u'):
        add(f'simd_prefix_{op} r14l, r6l', 'subop-spaces')
    for op in ('iadd', 'fadd', 'fmul'):
        add(f'quad_prefix_{op} r14l, r6l', 'subop-spaces')
    for op1 in (0, 1):
        for op2 in (0x0000, 0x1000, 0x2000, 0x3000, 0x4000, 0x5000, 0x6000, 0x7000, 0x0004, 0x0008, 0x0010, 0x0014, 0x0018, 0x001c):
            add(raw(f'b47_1={op1},b26_16={op2:#x}', 'simd_iadd r14, r6'), 'subop-spaces', 'may_fault')
    # moves
    for v in ('0', '1', '65535', '305419896', '4294967295'):
        add(f'mov_imm r14, {v}, 0b0', 'first-agx-instruction')
    add('mov_imm r14l, 4660', 'first-agx-instruction')
    return F


def _want(t):
    """disassembly applegpu prints for alias-producing forms (agx_loop.encode(text, want))"""
    if t.startswith('bitop '):
        tt = t.split()[1].rstrip(',')
        alias = {'0001': 'and', '0111': 'or', '0110': 'xor', '1110': 'nand', '1000': 'nor', '1001': 'xnor'}.get(tt)
        rest = t.split(', ', 1)[1]
        if alias: return f'{alias} {rest}'
        if tt in ('0011', '1100'): return t.replace('bitop', 'bitop_mov_a', 1)
    return None


