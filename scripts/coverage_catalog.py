# Timing: every ALU form whose destination and first source have the same width becomes an instruction-bench form
# (dependent chain through r{d}); recorded with run_bench's latency / simd_issue / gpu modes.

def bench_template(t):
    import re
    parts = t.split(' ', 1)
    if len(parts) < 2 or ',' not in parts[1]:
        return None
    ops = [o.strip() for o in parts[1].split(',')]
    first_reg = next((i for i, o in enumerate(ops) if re.fullmatch(r'r\d+[lh]?(_r\d+)?(\.[a-z.]+)?', o)), None)
    if first_reg is None or not ops[first_reg].startswith('r14'):
        return None
    d = ops[first_reg].split('.')[0]
    src = next((o for o in ops[first_reg + 1:] if re.fullmatch(r'r6[lh]?(_r7)?(\.[a-z.]+)?', o)), None)
    if src is None:
        return None
    s_base = src.split('.')[0]
    if (d.endswith('l') or d.endswith('h')) != (s_base.endswith('l') or s_base.endswith('h')) or ('_' in d) != ('_' in s_base):
        return None
    tmpl = t.replace(d, 'r{d}' + ('l' if d.endswith('l') else '') if '_' not in d else 'r{d}_r{d1}', 1)
    tmpl = tmpl.replace(s_base, ('r{d}' + ('l' if s_base.endswith('l') else 'h' if s_base.endswith('h') else '')) if '_' not in s_base else 'r{d}_r{d1}', 1)
    tmpl = re.sub(r'\br8_r9\b', 'r20_r21', tmpl)
    tmpl = re.sub(r'\br7\b', 'r20', tmpl); tmpl = re.sub(r'\br8\b', 'r22', tmpl); tmpl = re.sub(r'\br9\b', 'r21', tmpl)
    return tmpl


SFU = ('rcp', 'rsqrt', 'rsqrt_special', 'log2', 'exp2', 'sin_pt_1', 'sin_pt_2', 'floor', 'ceil', 'trunc', 'rint')


def bench_class(t, tmpl):
    """run_bench class (sets the constants r24..r27 and the chain's start value)"""
    op = t.split()[0].split('.')[0]
    if '{d1}' in tmpl: return 'int64'
    if op.startswith(('simd_', 'quad_', 'icmp_ballot', 'fcmp_ballot', 'icmp_quad', 'fcmp_quad')): return 'simd'
    if op in SFU or t.startswith('@b28_6'): return 'sfu'
    if op == 'convert' or 'convert' in t: return 'convert'
    if op.startswith(('fadd', 'fmul', 'fmadd', 'fcmpsel')): return 'half' if 'r{d}l' in tmpl else 'float'
    if op in ('bfi', 'bfeil', 'extr', 'shlhi', 'shrhi', 'asr', 'asrh', 'bitrev', 'popcount', 'ffs', 'intl'): return 'bitfield'
    if op == 'icmpsel': return 'select'
    if op == 'mov_imm': return 'move'
    return 'int'


def timing_cases(alu):
    out = []
    for t, finding, risk in alu:
        tmpl = bench_template(t)
        if tmpl is None or risk != 'safe' or _want(t):   # alias forms (bitop -> and/or/...) are benched under their alias
            continue
        cls = bench_class(t, tmpl)
        out.append(Case(f'bench/{_name(t)}', 'bench', 'instruction-bench', 'safe', 'timing', t,
                        lambda tmpl=tmpl, cls=cls: {'template': tmpl, 'class': cls}, []))
    return out


